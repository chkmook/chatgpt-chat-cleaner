async (page) => {
  const checks = [];
  const verify = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await page.goto('http://127.0.0.1:4173');
  const ui = page.getByRole('region', { name: '대화 삭제', exact: true });
  const first = page.locator('[data-id="demo-1"] a');
  const checkbox = page.getByRole('checkbox', { name: '연구 아이디어 정리 선택', exact: true });
  const count = () => ui.locator('#count').textContent();
  await ui.waitFor();
  const reset = await page.evaluate(() => {
    const probe = document.createElement('input'); probe.type = 'checkbox'; document.body.append(probe);
    const value = getComputedStyle(probe).appearance; probe.remove(); return value;
  });
  verify(reset === 'none', 'negative control: host CSS removes ordinary native checkbox appearance');
  verify(await page.locator('[data-chat-delete-checkbox] input').first().evaluate(n => getComputedStyle(n).appearance !== 'none'), 'injected checkbox retains visible native appearance despite the host CSS reset');
  await first.click();
  verify(await page.evaluate(() => window.fixtureNavigations) === 1, 'normal mode keeps native conversation navigation');
  await ui.getByRole('switch').check();
  await page.locator('#history').evaluate(n => { window.fixtureCapturedClicks = 0; n.addEventListener('click', () => window.fixtureCapturedClicks++, true); });
  await first.click();
  verify(await checkbox.isChecked() && await count() === '1/30', 'clicking the title selects the conversation');
  verify(await page.evaluate(() => window.fixtureNavigations) === 1 && await page.evaluate(() => window.fixtureCapturedClicks) === 0, 'selection blocks the native router before its capture handler');
  await first.click();
  verify(await checkbox.isChecked() === false && await count() === '0/30', 'clicking the title again deselects exactly once');
  await page.locator('[data-id="demo-1"]').click({ position: { x: 3, y: 3 } });
  verify(await checkbox.isChecked(), 'clicking row padding selects the conversation');
  await first.press('Enter');
  verify(await checkbox.isChecked() === false, 'Enter toggles a focused title without navigation');
  await first.press('Space');
  verify(await checkbox.isChecked(), 'Space selects a focused title');
  await page.locator('[data-id="demo-1"] [data-chat-delete-checkbox]').click({ position: { x: 2, y: 2 } });
  verify(await checkbox.isChecked() === false, 'the enlarged checkbox label toggles only once');
  await checkbox.check();
  verify(await count() === '1/30', 'direct checkbox selection still updates the selection count');
  await page.locator('#trigger-demo-2').click();
  await page.getByRole('menu').waitFor();
  verify(await page.getByRole('menu').count() === 1, 'native conversation menu remains usable in selection mode');
  await page.getByRole('menu').press('Escape');
  await ui.getByRole('button', { name: '삭제', exact: true }).click();
  await first.evaluate(n => n.click());
  verify(await count() === '1/30', 'selection and navigation stay locked while confirmation is open');
  await ui.getByRole('button', { name: '취소', exact: true }).click();
  await ui.getByRole('button', { name: '전체 선택', exact: true }).click();
  verify(await count() === '30/30', 'select all remains usable with row capture enabled');
  await ui.getByRole('button', { name: '해제', exact: true }).click();
  await page.evaluate(() => addChat('demo-31', '동적으로 추가된 대화'));
  const added = page.getByRole('checkbox', { name: '동적으로 추가된 대화 선택', exact: true });
  await added.waitFor();
  await page.locator('[data-id="demo-31"] a').click();
  verify(await added.isChecked() && await count() === '1/31', 'newly loaded rows also support title selection');
  await page.locator('[data-id="project-1"] a').click();
  verify(await count() === '1/31' && await page.evaluate(() => window.fixtureNavigations) === 2, 'excluded project conversations keep their native behavior');
  await ui.getByRole('switch').uncheck();
  await first.click();
  verify(await page.evaluate(() => window.fixtureNavigations) === 3, 'switching selection off restores normal navigation');
  await page.evaluate(() => {
    const legacy = document.createElement('div'); legacy.id = 'chat-tidy-root';
    const button = document.createElement('button'); button.className = 'launcher'; button.textContent = '대화 정리';
    legacy.attachShadow({ mode: 'open' }).append(button); document.body.append(legacy);
  });
  await page.waitForFunction(() => !document.getElementById('chat-tidy-root'));
  verify(await page.locator('#chat-tidy-root').count() === 0, 'obsolete floating launcher is removed if an old extension injects it');
  verify(await page.evaluate(() => window.fixtureActions.length) === 0, 'selection checks never delete or archive a conversation');
  await ui.getByRole('switch').check();
  await first.click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: 'output/playwright/v0.4.0-selection.png', scale: 'css' });
  return { passed: checks.length, checks, scope: 'Local fixture selection and navigation only; no account mutations' };
}
