async (page) => {
  const passed = [];
  const verify = (condition, name) => { if (!condition) throw new Error(name); passed.push(name); };
  const ui = page.getByRole('region', { name: '대화 삭제', exact: true });
  const actions = () => page.evaluate(() => window.fixtureActions);
  const box = (title) => page.getByRole('checkbox', { name: `${title} 선택`, exact: true });
  const status = (text) => ui.locator('#status').filter({ hasText: text }).waitFor({ timeout: 45000 });
  async function fresh(scenario = 'normal', language = 'ko', trigger = 'pointerdown') {
    await page.goto('http://127.0.0.1:4173');
    await page.locator('#scenario').selectOption(scenario);
    await page.locator('#language').selectOption(language);
    await page.locator('#trigger').selectOption(trigger);
    await ui.getByRole('switch', { name: '대화 선택', exact: true }).check();
  }
  await page.goto('http://127.0.0.1:4173');
  await ui.waitFor();
  verify(await page.locator('#chat-delete-controls').evaluate(n => !!n.closest('nav') && getComputedStyle(n).position === 'static'), 'controls are inline in the native chat sidebar');
  verify(await ui.getByRole('switch').isChecked() === false, 'selection starts disabled');
  verify(await box('연구 아이디어 정리').isVisible() === false, 'row checkboxes are hidden until selection is enabled');
  verify(await page.locator('#chat-tidy-root').count() === 0 && !(await ui.innerText()).includes('가볍게'), 'no floating panel, brand, version, or slogan');
  await page.locator('#trigger-demo-1').evaluate(n => n.click());
  verify(await page.getByRole('menu').count() === 0, 'regression control: click alone cannot open the current pointerdown menu');
  await ui.getByRole('switch').check();
  verify(await page.getByRole('checkbox').count() === 30, 'thirty ordinary history rows have checkboxes; project and message links are excluded');
  verify(await ui.getByRole('button', { name: '삭제', exact: true }).isDisabled(), 'zero selection cannot delete');
  await box('연구 아이디어 정리').check();
  verify(await page.evaluate(() => window.fixtureNavigations) === 0, 'selecting a row never opens its conversation');
  await ui.getByRole('switch').uncheck();
  await ui.getByRole('switch').check();
  verify(await box('연구 아이디어 정리').isChecked() === false, 'turning selection off clears selected targets');
  await box('연구 아이디어 정리').check();
  await box('주간 회의 메모').check();
  await ui.getByRole('button', { name: '삭제', exact: true }).click();
  verify(JSON.stringify(await ui.locator('#targets li').allTextContents()) === JSON.stringify(['연구 아이디어 정리', '주간 회의 메모']), 'inline confirmation lists exactly the selected titles');
  await ui.getByRole('button', { name: '취소', exact: true }).click();
  verify((await actions()).length === 0, 'cancelling inline confirmation submits nothing');
  await ui.getByRole('button', { name: '해제', exact: true }).click();
  await ui.getByRole('button', { name: '전체 선택', exact: true }).click();
  await ui.getByRole('button', { name: '삭제', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/v0.2.4-confirmation.png', scale: 'css' });
  await ui.getByRole('button', { name: '30개 삭제', exact: true }).click();
  await status('삭제 30/30 · 완료');
  verify(JSON.stringify(await actions()) === JSON.stringify(Array.from({ length: 30 }, (_, i) => ({ id: `demo-${i + 1}`, action: 'delete' }))), '30/30 deletion works with pointerdown menus and the current plain Korean confirmation paragraph');
  verify(await page.locator('[data-id="project-1"]').count() === 1, 'bulk deletion leaves the project conversation untouched');
  verify(await page.evaluate(() => window.fixtureMenuCount) === 30, 'each selected menu opens once without retries');

  await fresh('normal', 'en', 'click');
  await box('Python 코드 질문').check();
  await ui.getByRole('button', { name: '삭제', exact: true }).click();
  await ui.getByRole('button', { name: '1개 삭제', exact: true }).click();
  await status('삭제 1/1 · 완료');
  verify(JSON.stringify(await actions()) === JSON.stringify([{ id: 'demo-3', action: 'delete' }]), 'English deletion and legacy click-based triggers remain supported');

  for (const scenario of ['mismatch', 'substring']) {
    await fresh(scenario);
    await box('연구 아이디어 정리').check();
    await ui.getByRole('button', { name: '삭제', exact: true }).click();
    await ui.getByRole('button', { name: '1개 삭제', exact: true }).click();
    await status('확인창의 대화 제목이 일치하지 않아');
    verify((await actions()).length === 0, `${scenario}: wrong or partially matching title cannot authorize deletion`);
  }
  await fresh('unknown');
  await box('연구 아이디어 정리').check();
  await ui.getByRole('button', { name: '보관', exact: true }).click();
  await ui.getByRole('button', { name: '1개 보관', exact: true }).click();
  await status('삭제·보관 메뉴를 확실히 찾지 못해');
  verify((await actions()).length === 0, 'unknown menu cannot trigger a guessed action');
  await fresh('wrong-owner');
  await box('연구 아이디어 정리').check();
  await ui.getByRole('button', { name: '보관', exact: true }).click();
  await ui.getByRole('button', { name: '1개 보관', exact: true }).click();
  await status('대화 메뉴를 확인하지 못해');
  verify((await actions()).length === 0, 'a menu labelled by a different trigger is rejected');

  await page.clock.install();
  await fresh('stalled');
  await box('연구 아이디어 정리').check();
  await box('주간 회의 메모').check();
  await ui.getByRole('button', { name: '보관', exact: true }).click();
  await ui.getByRole('button', { name: '2개 보관', exact: true }).click();
  await page.waitForFunction(() => window.fixtureActions.length === 1);
  await page.clock.runFor(61000);
  await status('보관 0/2 · ChatGPT 처리 결과를 60초 안에 확인하지 못해');
  verify((await actions()).length === 1 && await page.locator('[data-id="demo-2"]').count() === 1, 'an unconfirmed result stops the queue without claiming success or retrying');
  await page.clock.resume();
  await fresh('slow');
  await box('연구 아이디어 정리').check();
  await box('주간 회의 메모').check();
  await ui.getByRole('button', { name: '보관', exact: true }).click();
  await ui.getByRole('button', { name: '2개 보관', exact: true }).click();
  await page.waitForFunction(() => window.fixtureActions.length === 1);
  await ui.getByRole('button', { name: '중지', exact: true }).click();
  await status('보관 1/2 · 중지됨');
  verify((await actions()).length === 1, 'stop leaves the next selected conversation untouched');

  await fresh();
  await page.evaluate(() => addChat('demo-31', '새로 불러온 대화'));
  await box('새로 불러온 대화').waitFor();
  verify(await box('새로 불러온 대화').isChecked() === false, 'new sidebar rows receive unchecked checkboxes automatically');
  await box('연구 아이디어 정리').check();
  await page.locator('[data-id="demo-1"]').evaluate(n => n.remove());
  await page.waitForFunction(() => document.querySelector('#chat-delete-controls').shadowRoot.querySelector('#delete').disabled);
  verify(await ui.getByRole('button', { name: '삭제', exact: true }).isDisabled(), 'removed rows cannot retain a stale actionable selection');
  await page.locator('#reset').click();
  await box('연구 아이디어 정리').waitFor();
  verify(await page.locator('[data-chat-delete-checkbox]').count() === 30 && await page.locator('#chat-delete-controls').count() === 1, 'sidebar rerender restores one checkbox per chat and one toolbar');
  verify(await page.locator('#chat-delete-controls').evaluate(n => !n.shadowRoot.querySelector('img')), 'HTML-like chat titles are never injected as HTML');
  await box('연구 아이디어 정리').check();
  await ui.getByRole('button', { name: '삭제', exact: true }).click();
  await page.locator('[data-id="demo-1"] a').evaluate(n => { n.textContent = '다른 제목'; n.setAttribute('aria-label', '다른 제목'); });
  await ui.getByRole('button', { name: '1개 삭제', exact: true }).click();
  await status('대상 대화가 바뀌었거나');
  verify((await actions()).length === 0, 'a renamed target after confirmation is not processed');

  await fresh();
  await page.locator('#history').evaluate(n => [...n.children].filter(row => row.dataset.id !== 'demo-1').forEach(row => row.remove()));
  await page.waitForFunction(() => document.querySelector('#chat-delete-controls').shadowRoot.querySelector('#count').textContent === '0/1');
  await box('연구 아이디어 정리').check();
  await ui.getByRole('button', { name: '삭제', exact: true }).click();
  await ui.getByRole('button', { name: '1개 삭제', exact: true }).click();
  await status('삭제 1/1 · 완료');
  verify(await page.locator('#history [data-id]').count() === 0, 'the last remaining row can be deleted even when its list collapses to zero height');
  verify(await ui.isVisible() && await ui.getByRole('button', { name: '삭제', exact: true }).isDisabled(), 'empty history keeps the inline result visible with no stale selection');

  await page.setViewportSize({ width: 390, height: 720 });
  await fresh();
  const bounds = await ui.boundingBox();
  verify(bounds.x >= 0 && bounds.x + bounds.width <= 250, 'inline controls fit a narrow native sidebar');
  await page.screenshot({ path: 'output/playwright/v0.2.4-narrow.png', scale: 'css' });
  await page.setViewportSize({ width: 1280, height: 900 });
  await fresh();
  await box('연구 아이디어 정리').check();
  await box('주간 회의 메모').check();
  await page.screenshot({ path: 'output/playwright/v0.2.4-inline.png', scale: 'css' });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: 'output/playwright/v0.2.4-dark.png', scale: 'css' });
  await page.emulateMedia({ colorScheme: 'light' });
  return { passed: passed.length, checks: passed, scope: 'Local fixtures; pointerdown-only portalled menu, aria-labelledby ownership, plain Korean delete paragraph observed in live UI' };
}
